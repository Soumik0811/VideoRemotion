import assert from 'node:assert/strict';
import fs from 'node:fs';
const e=JSON.parse(fs.readFileSync(new URL('../src/data/bakery-episode.json',import.meta.url),'utf8'));
const f=e.financials;
assert.equal(f.sales-f.productionCost,f.grossProfit,'Gross profit must equal sales minus production cost');
assert.equal(f.startingCash,f.productionCost,'Both spend their initial funds on the first batch');
assert.equal(f.noahCashReceived+f.unpaidInvoice,f.sales,'Noah’s revenue is cash plus receivables');
assert.equal(f.oliverCashReceived,f.sales);
assert.ok(f.oliverCashReceived>=f.productionCost);
assert.equal(e.scenes.length,6);
assert.equal(e.scenes[0].start,0);
e.scenes.forEach((s,i)=>{assert.ok(s.end>s.start);assert.equal(s.end,e.scenes[i+1]?.start??e.durationSeconds);});
assert.equal(e.width,1080);assert.equal(e.height,1920);assert.equal(e.fps,30);
assert.ok(e.durationSeconds>=75&&e.durationSeconds<=90);
e.captions.forEach((c,i)=>{assert.ok(c.start>=0&&c.end>c.start&&c.end<=e.durationSeconds);assert.ok(c.start>=(e.captions[i-1]?.end??0));});
const flatten=s=>s.replace(/\s+/g,' ').trim();
assert.equal(flatten(e.captions.map(c=>c.text).join(' ')),flatten(e.narration.text),'Captions must preserve the exact narration');
assert.equal(flatten(e.narration.sentences.map(c=>c.text).join(' ')),flatten(e.narration.text));
assert.ok(e.narration.src!== 'audio/narration.wav','Do not use the previous episode’s narration');
e.soundEvents.forEach(a=>{assert.ok(a.at>=0&&a.at<e.durationSeconds);assert.ok(fs.existsSync(new URL(`../public/audio/bakery/${a.sound}.wav`,import.meta.url)));});
assert.ok(fs.existsSync(new URL(`../public/${e.assets.music}`,import.meta.url)));
console.log(`Bakery verified: 6 scenes, ${e.captions.length} exact-script subtitle groups, ${e.durationSeconds}s. Sales $${f.sales} − cost $${f.productionCost} = gross profit $${f.grossProfit}. Captions: ${e.narration.timing}.`);
